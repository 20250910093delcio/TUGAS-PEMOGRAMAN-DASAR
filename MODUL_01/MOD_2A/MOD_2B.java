public class MOD_2B {
    public static void main(String[] args){
        int a = 6, b = 4;
        System.out.println("nilai a + b = " + (a + b));
        System.out.println("nilai a - b = " + (a - b));
        System.out.println("nilai a * b = " + (a * b));
        System.out.println("nilai a / b = " + (a / b));
        System.out.println("nilai a % b = " + (a % b));
        System.out.println("nilai ++a = " + (++a));
        System.out.println("nilai  b++ = " + (b++));
        System.out.println("nilai b-- = " + (b--));
        System.out.println("nilai --a = " + (--a));
        
    }
}
